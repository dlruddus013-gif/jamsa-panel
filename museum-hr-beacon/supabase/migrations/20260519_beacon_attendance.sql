-- ── 0. 최소 스키마 보장 (이미 있다면 무시) ───────────────────────
create table if not exists public.staff (
  id            bigint generated by default as identity primary key,
  name          text not null,
  created_at    timestamptz not null default now()
);

create table if not exists public.attendance (
  id            bigint generated by default as identity primary key,
  staff_id      bigint references public.staff(id) on delete cascade,
  checked_in_at timestamptz not null default now(),
  checked_out_at timestamptz,
  created_at    timestamptz not null default now()
);

-- ── 1. staff 컬럼 확장 ───────────────────────────────────────────
alter table public.staff
  add column if not exists beacon_namespace text,
  add column if not exists beacon_instance  text,
  add column if not exists beacon_mac       text,
  add column if not exists dept_code        smallint,
  add column if not exists contract_type    text,            -- 정규직/계약직/시급제/외주
  add column if not exists visa_type        text,            -- E-9 / H-2 / F-4 등
  add column if not exists visa_expires_at  date,
  add column if not exists insurance_status text,            -- 가입/미가입/만료
  add column if not exists country          text,
  add column if not exists phone            text,
  add column if not exists hire_date        date;

-- beacon_instance는 1인 1비콘 → UNIQUE
do $$
begin
  if not exists (
    select 1 from pg_indexes
    where schemaname = 'public'
      and indexname  = 'staff_beacon_instance_key'
  ) then
    create unique index staff_beacon_instance_key
      on public.staff (beacon_instance)
      where beacon_instance is not null;
  end if;
end$$;

create index if not exists staff_dept_code_idx on public.staff (dept_code);

-- dept_code CHECK (1~255, 0x01~0xFF)
alter table public.staff
  drop constraint if exists staff_dept_code_chk;
alter table public.staff
  add constraint staff_dept_code_chk
  check (dept_code is null or (dept_code between 1 and 255));

-- contract_type CHECK
alter table public.staff
  drop constraint if exists staff_contract_type_chk;
alter table public.staff
  add constraint staff_contract_type_chk
  check (contract_type is null or contract_type in ('정규직','계약직','시급제','외주'));

-- ── 2. attendance 컬럼 확장 ─────────────────────────────────────
