-- ── 3. 부서 마스터 (UI/뱃지용 — 선택) ───────────────────────────
create table if not exists public.beacon_dept (
  code   smallint primary key,
  name   text not null,
  color  text,
  note   text
);

insert into public.beacon_dept (code, name, color, note) values
