-- ── 1. attendance 자동 체크아웃 컬럼 ────────────────────────────
alter table public.attendance
  add column if not exists last_seen_at timestamptz,
  add column if not exists auto_closed  boolean default false,
  add column if not exists close_reason text;   -- 'auto-timeout' / 'manual' / 'override'

create index if not exists attendance_open_idx
  on public.attendance (staff_id, checked_in_at)
  where checked_out_at is null;

-- ── 2. 매분 실행할 자동 체크아웃 함수 ───────────────────────────
-- 5분 이상 last_seen_at 갱신 없는 open attendance → 자동 종료
create or replace function public.auto_close_stale_attendance()
returns integer language plpgsql security definer as $$
declare
  closed_count integer;
begin
  update public.attendance
     set checked_out_at = coalesce(last_seen_at, checked_in_at),
         auto_closed    = true,
         close_reason   = 'auto-timeout'
   where checked_out_at is null
     and coalesce(last_seen_at, checked_in_at) < now() - interval '5 minutes';
  get diagnostics closed_count = row_count;
  return closed_count;
end$$;

