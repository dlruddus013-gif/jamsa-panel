-- ── 7. 트리거 함수: attendance.dept_code 자동 채움 ───────────────
create or replace function public.attendance_fill_dept()
returns trigger language plpgsql as $$
begin
  if new.dept_code is null and new.staff_id is not null then
    select s.dept_code into new.dept_code from public.staff s where s.id = new.staff_id;
  end if;
  return new;
end$$;

drop trigger if exists trg_attendance_fill_dept on public.attendance;
create trigger trg_attendance_fill_dept
  before insert or update on public.attendance
  for each row execute function public.attendance_fill_dept();

-- ── 8. 헬퍼 함수 ────────────────────────────────────────────────
create or replace function public.current_staff_dept_code()
returns smallint language sql stable security definer as $$
  select dept_code from public.staff where auth_uid = auth.uid() limit 1;
$$;

create or replace function public.current_user_is_admin_dept()
returns boolean language sql stable security definer as $$
  select coalesce(public.current_staff_dept_code() = 1, false)
      or coalesce((auth.jwt() ->> 'role') = 'service_role', false);
$$;

-- ── 9. RLS 활성화 + 정책 ────────────────────────────────────────
alter table public.staff       enable row level security;
