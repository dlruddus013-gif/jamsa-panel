drop policy if exists beacon_dept_write on public.beacon_dept;
create policy beacon_dept_write on public.beacon_dept for all
  using (public.current_user_is_admin_dept()) with check (public.current_user_is_admin_dept());

-- staff
drop policy if exists staff_select on public.staff;
create policy staff_select on public.staff for select using (
  public.current_user_is_admin_dept()
  or auth_uid = auth.uid()
  or (dept_code = public.current_staff_dept_code() and dept_code <> 3)
);
drop policy if exists staff_insert on public.staff;
create policy staff_insert on public.staff for insert with check (public.current_user_is_admin_dept());
drop policy if exists staff_update on public.staff;
create policy staff_update on public.staff for update
  using (public.current_user_is_admin_dept()) with check (public.current_user_is_admin_dept());
drop policy if exists staff_delete on public.staff;
create policy staff_delete on public.staff for delete using (public.current_user_is_admin_dept());

-- attendance
drop policy if exists attendance_select on public.attendance;
create policy attendance_select on public.attendance for select using (
  public.current_user_is_admin_dept()
  or (dept_code <> 3 and dept_code = public.current_staff_dept_code())
  or staff_id in (select id from public.staff where auth_uid = auth.uid())
);
drop policy if exists attendance_insert on public.attendance;
create policy attendance_insert on public.attendance for insert with check (
  public.current_user_is_admin_dept()
  or staff_id in (select id from public.staff where auth_uid = auth.uid())
);
drop policy if exists attendance_update on public.attendance;
create policy attendance_update on public.attendance for update
  using (public.current_user_is_admin_dept()) with check (public.current_user_is_admin_dept());
drop policy if exists attendance_delete on public.attendance;
create policy attendance_delete on public.attendance for delete using (public.current_user_is_admin_dept());

-- ── 10. 뷰 (DROP + CREATE — 컬럼 중복 절대 방지) ───────────────
drop view if exists public.v_attendance_today cascade;
create view public.v_attendance_today as
  select a.id,
         a.staff_id,
         a.checked_in_at,
         a.checked_out_at,
         a.raw_rssi,
         a.estimated_distance_m,
         a.beacon_mac          as att_beacon_mac,
         a.beacon_namespace    as att_beacon_namespace,
         a.beacon_instance     as att_beacon_instance,
         a.gateway_id,
         a.dept_code           as att_dept_code,
         s.name                as staff_name,
         s.dept_code           as staff_dept_code,
         s.beacon_instance     as staff_beacon_instance,
         s.contract_type       as staff_contract_type,
         s.visa_type           as staff_visa_type,
         s.visa_expires_at     as staff_visa_expires_at,
         s.country             as staff_country,
         d.name                as dept_name,
         d.color               as dept_color
    from public.attendance a
    left join public.staff       s on s.id   = a.staff_id
    left join public.beacon_dept d on d.code = coalesce(a.dept_code, s.dept_code)
   where a.checked_in_at::date = current_date
   order by a.checked_in_at desc;

drop view if exists public.v_foreign_workers cascade;
create view public.v_foreign_workers as
  select s.id, s.name, s.dept_code,
         s.beacon_namespace, s.beacon_instance, s.beacon_mac,
         s.contract_type, s.visa_type, s.visa_expires_at,
         s.insurance_status, s.country, s.phone, s.hire_date, s.auth_uid,
         d.name  as dept_name,
         d.color as dept_color,
         case
           when s.visa_expires_at is null                            then 'unknown'
           when s.visa_expires_at <  current_date                     then 'expired'
           when s.visa_expires_at <  current_date + interval '30 day' then 'warning'
           when s.visa_expires_at <  current_date + interval '90 day' then 'soon'
           else 'ok'
         end as visa_status
    from public.staff s
    left join public.beacon_dept d on d.code = s.dept_code
   where s.dept_code = 3;

-- ── 11. Phase 2 — 자동 체크아웃 함수 + 결근 테이블 ──────────────
create or replace function public.auto_close_stale_attendance()
returns integer language plpgsql security definer as $$
declare closed_count integer;
begin
  update public.attendance
     set checked_out_at = coalesce(last_seen_at, checked_in_at),
         auto_closed    = true,
         close_reason   = 'auto-timeout'
   where checked_out_at is null
     and coalesce(last_seen_at, checked_in_at) < now() - interval '5 minutes';
  get diagnostics closed_count = row_count;
  return closed_count;
end$$;

create table if not exists public.absence_records (
  id         bigint generated by default as identity primary key,
  staff_id   bigint not null references public.staff(id) on delete cascade,
  date       date not null,
  type       text not null check (type in ('absent','late','early_leave','sick','vacation','public_holiday')),
  minutes    integer,
  note       text,
  created_at timestamptz not null default now(),
  unique (staff_id, date, type)
);

create index if not exists absence_records_date_idx on public.absence_records (date desc);

