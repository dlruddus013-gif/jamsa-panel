-- ── 12. Phase 2 — 근무시간 뷰 ──────────────────────────────────
drop view if exists public.v_work_hours cascade;
create view public.v_work_hours as
with closed as (
  select a.*,
         coalesce(a.checked_out_at, now()) as out_at,
         extract(epoch from (coalesce(a.checked_out_at, now()) - a.checked_in_at)) / 60.0 as minutes_total
    from public.attendance a
   where a.checked_in_at is not null
)
select c.id, c.staff_id, c.dept_code, c.checked_in_at, c.out_at,
       round(c.minutes_total::numeric, 1)                as minutes_total,
       round((c.minutes_total / 60.0)::numeric, 2)       as hours_total,
       case
         when extract(hour from c.checked_in_at) >= 22 or extract(hour from c.out_at) < 6
         then round((c.minutes_total * 1.5 / 60.0)::numeric, 2)
         else round((c.minutes_total / 60.0)::numeric, 2)
       end                                                as hours_paid_est,
       case when extract(dow from c.checked_in_at) = 0 then true else false end as is_holiday,
       c.auto_closed, c.close_reason
  from closed c;

drop view if exists public.v_daily_summary cascade;
create view public.v_daily_summary as
select s.id              as staff_id,
       s.name            as staff_name,
       s.dept_code,
       d.name            as dept_name,
       a.checked_in_at::date as work_date,
       min(a.checked_in_at)  as first_in,
       max(a.out_at)         as last_out,
       round(sum(a.minutes_total)::numeric / 60.0, 2) as total_hours,
       count(*) filter (where a.auto_closed) as auto_closed_sessions
  from public.staff s
  left join public.beacon_dept d on d.code = s.dept_code
  left join public.v_work_hours a on a.staff_id = s.id
 group by s.id, s.name, s.dept_code, d.name, a.checked_in_at::date;

